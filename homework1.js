// 1. 'number' + 3 + 3

// 'number' — це текст.
// Якщо до тексту додати число, число теж стає текстом.
// Спочатку отримуємо: 'number3'.
// Потім додаємо ще 3.
// Отримуємо: 'number33'.
console.log('number' + 3 + 3); // number33

// 2. null + 3

// null перетворюється на число 0.
// Потім 0 додається до 3.
// Отримуємо 3.
console.log(null + 3); // 3

// 3. 5 && "qwerty"

// Оператор && перевіряє перше значення.
// Число 5 означає true.
// Тому JavaScript переходить до другого значення.
// Друге значення — "qwerty".
// Саме його і отримуємо.
console.log(5 && "qwerty"); // qwerty

// 4. +"40" + +"2" + "hillel"

// +"40" перетворює текст "40" на число 40.
// +"2" перетворює текст "2" на число 2.
// Спочатку додаємо числа: 40 + 2 = 42.
// Потім додаємо текст "hillel".
// Число 42 стає текстом.
// Отримуємо "42hillel".
console.log(+"40" + +"2" + "hillel"); // 42hillel

// 5. '10' - 5 === 6

// "10" стає числом 10.
// 10 - 5 = 5.
// 5 не дорівнює 6.
// Отримуємо false.
console.log('10' - 5 === 6); // false

// 6. true + false

// true перетворюється на число 1.
// false перетворюється на число 0.
// Додаємо: 1 + 0 = 1.
// Отримуємо число 1.
console.log(true + false); // 1

// 7. '4px' - 3

// "4px" — це текст.
// JavaScript намагається зробити з нього число.
// Але "4px" не можна перетворити на число.
// Тому отримуємо NaN.
console.log('4px' - 3); // NaN

// 8. '4' - 3

// "4" — це текст.
// JavaScript робить із нього число 4.
// 4 - 3 = 1.
// Отримуємо 1.
console.log('4' - 3); // 1

// 9. '6' + 3 ** 0

// Спочатку рахуємо 3 ** 0.
// Будь-яке число в степені 0 дорівнює 1.
// Потім додаємо до "6" число 1.
// Число 1 стає текстом.
// Отримуємо "61".
console.log('6' + 3 ** 0); // "61"

// 10. 12 / '6'

// "6" — це текст.
// JavaScript робить із нього число 6.
// 12 / 6 = 2.
// Отримуємо 2.
console.log(12 / '6'); // 2

// 11. '10' + (5 === 6)

// Спочатку перевіряємо:
// Чи 5 дорівнює 6?
// Ні.
// Отримуємо false.
// Потім додаємо false до "10".
// false стає текстом.
// Отримуємо "10false".
console.log('10' + (5 === 6)); // "10false"

// 12. null == ''

// null і порожній текст "" — це різні значення.
// Вони не рівні.
// Тому отримуємо false.
console.log(null == ''); // false

// 13. 3 ** (9 / 3)

// Спочатку рахуємо в дужках.
// 9 / 3 = 3.
// Потім рахуємо 3 у степені 3.
// 3 × 3 × 3 = 27.
// Отримуємо 27.
console.log(3 ** (9 / 3)); // 27

// 14. !!'false' == !!'true'

// "false" — це текст.
// "true" — теж текст.
// Будь-який непорожній текст має значення true.
// !! залишає значення true.
// Порівнюємо:
// true == true.
// Отримуємо true.
console.log(!!'false' == !!'true'); // true

// 15. 0 || '0' && 1

// Спочатку виконується &&.
// "0" — це текст, тому він має значення true.
// Отримуємо 1.
// Потім виконується ||.
// 0 має значення false.
// Тому повертається 1.
// Отримуємо 1.
console.log(0 || '0' && 1); // 1

// 16. (+null == false) < 1

// +null перетворюється на число 0.
// false теж перетворюється на число 0.
// 0 == 0 — це true.
// true перетворюється на число 1.
// 1 < 1 — це false.
// Отримуємо false.
console.log((+null == false) < 1); // false

// 17. false && true || true

// Спочатку виконується &&.
// false && true = false.
// Потім виконується ||.
// false || true = true.
// Отримуємо true.
console.log(false && true || true); // true

// 18. false && (false || true)

// Спочатку рахуємо в дужках.
// false || true = true.
// Потім:
// false && true = false.
// Отримуємо false.
console.log(false && (false || true)); // false

// 19. (+null == false) < 1 ** 5

// +null стає числом 0.
// false теж стає числом 0.
// 0 == 0 — це true.
// 1 ** 5 = 1.
// true стає числом 1.
// 1 < 1 — це false.
// Отримуємо false.
console.log((+null == false) < 1 ** 5); // false